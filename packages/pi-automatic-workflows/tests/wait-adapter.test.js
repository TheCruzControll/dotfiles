import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
test('fake-clock adapter persists, queues busy checks, restores pins, gates approval and suspends uncertain reloads',async()=>{
 const temp=fs.mkdtempSync(path.join(os.tmpdir(),'conductor-wait-'));
 const root=path.resolve(import.meta.dirname,'..');
 for(const dir of ['extension','lib','workflows','principles']) fs.cpSync(path.join(root,dir),path.join(temp,dir),{recursive:true});
 fs.writeFileSync(path.join(temp,'package.json'),'{"type":"module"}');
 const stub=path.join(temp,'node_modules/typebox');fs.mkdirSync(stub,{recursive:true});
 fs.writeFileSync(path.join(stub,'package.json'),'{"type":"module","exports":"./index.js"}');
 fs.writeFileSync(path.join(stub,'index.js'),'export const Type=new Proxy({}, {get:()=> (...args)=>args[0]});');
 const oldStore=process.env.PI_AUTOMATIC_WORKFLOWS_REVISION_STORE;
 process.env.PI_AUTOMATIC_WORKFLOWS_REVISION_STORE=path.join(temp,'store');
 const realNow=Date.now, realSet=globalThis.setTimeout, realClear=globalThis.clearTimeout;
 let now=1000,timer,idle=false, approved=false;
 Date.now=()=>now;globalThis.setTimeout=(fn,delay)=>(timer={fn,delay});globalThis.clearTimeout=()=>{timer=undefined;};
 try {
  const {default:install}=await import(pathToFileURL(path.join(temp,'extension/index.js')));
  const hooks=new Map(),tools=new Map(),commands=new Map(),entries=[],sent=[];
  const pi={on:(n,h)=>hooks.set(n,h),registerTool:t=>tools.set(t.name,t),registerCommand:(n,c)=>commands.set(n,c),appendEntry:(customType,data)=>entries.push({id:`e${entries.length}`,type:'custom',customType,data:structuredClone(data)}),events:{on:()=>{},emit:()=>{}},sendMessage:(m,o)=>{assert.ok(entries.at(-1).data.task.waits.some(j=>j.status==='checking'));sent.push({m,o});}};
  const ctx={cwd:temp,hasUI:true,isIdle:()=>idle,hasPendingMessages:()=>false,ui:{setStatus:()=>{},notify:()=>{},confirm:async()=>approved},sessionManager:{getBranch:()=>entries,getSessionId:()=> 'fixture'}};
  install(pi);await hooks.get('session_start')({},ctx);
  assert.equal(commands.get('workflow'),commands.get('conductor'));
  await tools.get('workflow_select').execute('s',{route:'feature',scope:'check reviewer',reason:'fixture'},null,null,ctx);
  const call=args=>tools.get('workflow_wait').execute('w',args,null,null,ctx);
  await call({action:'schedule',check:'Read reviewer',authorization:'User authorized read-only reviewer check',responseRef:'review:1',nextDue:2000,deadline:10000,maxAttempts:3});
  const fire=()=>{const current=timer;timer=undefined;current.fn();};
  now=2000;fire();assert.equal(sent.length,0);assert.equal(timer.delay,1000);
  idle=true;now=3000;fire();assert.equal(sent.length,1);assert.deepEqual(sent[0].o,{triggerTurn:true,deliverAs:'followUp'});
  const event={messageType:'custom',message:sent[0].m,systemPromptOptions:{sections:{}}};
  hooks.get('before_agent_start')(event,ctx);assert.match(event.systemPromptOptions.sections.automatic_workflow,/Existing permissions/);
  hooks.get('before_agent_start')(event,ctx);assert.match(event.systemPromptOptions.sections.automatic_workflow,/Stale/);
  assert.equal(hooks.get('tool_call')({toolName:'bash',input:{command:'must not run'}},ctx).block,true);
  await call({action:'outcome',state:'pending-review',responseRef:'review:2',nextDue:4000});
  now=4000;fire();assert.equal(sent.length,2);
  await call({action:'outcome',state:'approval-needed',responseRef:'review:3'});assert.equal(timer,undefined);
  await assert.rejects(call({action:'outcome',state:'accepted',responseRef:'not-approved'}),/Owner/);
  await assert.rejects(call({action:'approve'}),/Declined/);
  const approvalTask=structuredClone(entries.at(-1).data.task);
  await call({action:'cancel',id:approvalTask.waits[0].id});
  const cancelledHistory=structuredClone(entries.at(-1).data.task.waits);
  const reselected=await tools.get('workflow_select').execute('reselect',{route:'review',scope:'check reviewer',reason:'continue same task'},null,null,ctx);
  assert.ok(!reselected.isError);
  const continued=entries.at(-1).data.task;
  assert.equal(continued.taskId,approvalTask.taskId);
  assert.equal(continued.externalState,'approval-needed');
  assert.equal(continued.latestResponseRef,'review:3');
  assert.deepEqual(continued.waits,cancelledHistory);
  const completion=await tools.get('workflow_update').execute('complete',{action:'stage',value:'completed'},null,null,ctx);
  assert.equal(completion.isError,true);
  assert.match(completion.content[0].text,/not acceptance/);
  await assert.rejects(call({action:'schedule',check:'Must not schedule',authorization:'Read-only',responseRef:'review:3',nextDue:5000,deadline:10000,maxAttempts:1}),/approval gate/);
  approved=true;await call({action:'approve'});
  await call({action:'schedule',check:'Read approved reviewer',authorization:'Read-only check',responseRef:'review:3',nextDue:5000,deadline:10000,maxAttempts:2});
  await call({action:'outcome',state:'accepted',responseRef:'review:accepted'});
  assert.ok(entries.at(-1).data.task.waits.every(j=>j.status==='cancelled'));
  await call({action:'schedule',check:'Read next review',authorization:'Read-only',responseRef:'review:4',nextDue:5000,deadline:10000,maxAttempts:2});
  now=5000;fire();hooks.get('session_tree')({},ctx);
  assert.equal(entries.at(-1).data.task.waits.at(-1).status,'suspended');
  const suspended=entries.at(-1).data.task.waits.at(-1);
  await call({action:'cancel',id:suspended.id});
  await call({action:'schedule',check:'Expiry check',authorization:'Read-only',responseRef:'review:5',nextDue:6000,deadline:7000,maxAttempts:1});
  now=7000;fire();assert.equal(sent.length,3);assert.equal(entries.at(-1).data.task.waits.at(-1).status,'expired');assert.equal(timer,undefined);
  await call({action:'schedule',check:'Unrelated input safety',authorization:'Read-only',responseRef:'review:6',nextDue:8000,deadline:10000,maxAttempts:1});
  hooks.get('before_agent_start')({messageType:'user',prompt:'Different request',systemPromptOptions:{sections:{}}},ctx);
  assert.equal(entries.at(-1).data.task.waits.at(-1).status,'suspended');assert.equal(timer,undefined);
  await call({action:'cancel',id:entries.at(-1).data.task.waits.at(-1).id});
  await call({action:'outcome',state:'accepted',responseRef:'review:final-accepted'});
  const terminalHistory=structuredClone(entries.at(-1).data.task.waits);
  assert.ok(terminalHistory.some(j=>j.status==='expired'));
  assert.ok(terminalHistory.some(j=>j.status==='cancelled'));
  const completed=await tools.get('workflow_update').execute('complete',{action:'stage',value:'completed'},null,null,ctx);
  assert.ok(!completed.isError);
  hooks.get('session_shutdown')({},ctx);assert.equal(timer,undefined);
  await hooks.get('session_start')({},ctx);
  assert.deepEqual(entries.at(-1).data.task.waits,terminalHistory);
  const cleanup=await tools.get('workflow_update').execute('cleanup',{action:'stage',value:'cleanup'},null,null,ctx);
  assert.ok(!cleanup.isError);
  hooks.get('session_shutdown')({},ctx);assert.equal(timer,undefined);
 } finally {Date.now=realNow;globalThis.setTimeout=realSet;globalThis.clearTimeout=realClear;if(oldStore===undefined)delete process.env.PI_AUTOMATIC_WORKFLOWS_REVISION_STORE;else process.env.PI_AUTOMATIC_WORKFLOWS_REVISION_STORE=oldStore;}
});

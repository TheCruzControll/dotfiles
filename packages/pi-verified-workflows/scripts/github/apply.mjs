#!/usr/bin/env node
import { parseArgs } from 'node:util';

import {
  GUARDRAIL_EXIT_CODE,
  INTERNAL_EXIT_CODE,
  GuardrailStop,
  buildGuardrailEnvelope,
  buildSuccessEnvelope,
  helpEnvelope,
  isGuardrailStop,
  readJsonFile,
  writeDiagnostic,
  writeStdoutJson,
} from './common.mjs';
import { applyGithubPlan } from './apply-core.mjs';
import { loadTransport } from './transport.mjs';

const OPERATION = 'github:apply';

const HELP = helpEnvelope(
  OPERATION,
  'node ./scripts/github/apply.mjs --plan <approved-plan.json>',
  'Apply an approved GitHub issue mutation plan with stale-state checks and read-after-write verification.',
  {
    '--plan <path>': 'Required approved plan artifact generated by github:plan.',
    '--help': 'Show command usage as JSON.',
  },
);

async function main() {
  const { values } = parseArgs({
    options: {
      plan: { type: 'string' },
      help: { type: 'boolean', short: 'h' },
    },
    strict: true,
    allowPositionals: false,
  });

  if (values.help) {
    writeStdoutJson(HELP);
    return;
  }

  if (!values.plan) {
    throw new GuardrailStop('validation_failed', 'Missing required --plan argument.');
  }

  const plan = readJsonFile(values.plan);
  const transport = await loadTransport(process.env);
  const result = await applyGithubPlan({ plan, transport });

  const summary = `Applied ${result.stats.mutationCount} mutation(s) with ${result.stats.noOpCount} approved no-op(s).`;
  writeStdoutJson(
    buildSuccessEnvelope(OPERATION, summary, {
      result,
    }),
  );
}

main().catch((error) => {
  if (isGuardrailStop(error)) {
    writeDiagnostic(error.summary);
    writeStdoutJson(buildGuardrailEnvelope(OPERATION, error));
    process.exitCode = GUARDRAIL_EXIT_CODE;
    return;
  }

  writeDiagnostic(error instanceof Error ? error.message : String(error));
  writeStdoutJson({
    ok: false,
    operation: OPERATION,
    code: 'internal_error',
    summary: 'github:apply failed unexpectedly.',
    artifacts: [],
    warnings: [],
  });
  process.exitCode = INTERNAL_EXIT_CODE;
});
